/** Απλός έλεγχος μορφής: κρατάμε μόνο ό,τι μοιάζει με διεύθυνση, ποτέ αυθαίρετο κείμενο. */
function looksLikeIp(v: string): boolean {
  if (!v) return false;
  if (/^\d{1,3}(\.\d{1,3}){3}$/.test(v)) return true;        // IPv4
  return /^[0-9a-f:]{3,45}$/i.test(v) && v.includes(':');    // IPv6
}

/**
 * Η διεύθυνση του ανθρώπου που κάθεται μπροστά στην οθόνη.
 * Κενό αν δεν μπορούμε να την πούμε με βεβαιότητα — καλύτερα τίποτα παρά λάθος:
 * μια λάθος διεύθυνση φορτώνει το φρένο σε αθώο τρίτο.
 */
export function clientIpOf(request: Request, fallback?: string): string {
  const h = request.headers;

  const cf = (h.get('cf-connecting-ip') ?? '').trim();
  if (looksLikeIp(cf)) return cf;

  const real = (h.get('x-real-ip') ?? '').trim();
  if (looksLikeIp(real)) return real;

  // Πρώτο στοιχείο της αλυσίδας = ο αρχικός πελάτης.
  const first = (h.get('x-forwarded-for') ?? '').split(',')[0]?.trim() ?? '';
  if (looksLikeIp(first)) return first;

  const fb = (fallback ?? '').trim();
  return looksLikeIp(fb) ? fb : '';
}

/**
 * Οι κεφαλίδες που προωθούνται στο EALIDA. Κενό αντικείμενο όταν δεν ξέρουμε —
 * τότε το EALIDA κρατά τη δική του εκτίμηση αντί για δικό μας μάντεμα.
 *
 * ⚠️ Γράφουμε ΚΑΙ τα τρία με την ίδια τιμή: αν αύριο αλλάξει η σειρά προτίμησης
 * εκεί, δεν θα σπάσει σιωπηλά — δεν υπάρχει εκδοχή όπου διαλέγει «λάθος» κεφαλίδα.
 */
export function forwardIp(request: Request, fallback?: string): Record<string, string> {
  const ip = clientIpOf(request, fallback);
  if (!ip) return {};
  return { 'cf-connecting-ip': ip, 'x-real-ip': ip, 'x-forwarded-for': ip };
}
