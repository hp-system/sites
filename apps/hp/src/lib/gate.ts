//    μόνα δύο κρυφά που έφταναν στο site ήταν **δημόσια**, ενώ η αρχική τα διαφημίζει
//    ως κίνητρο εγγραφής. Το `home.ts` έγραφε ακόμα `=== true` και μετρούσε λιγότερα.
//
// ⛔ ΜΗΝ ΑΛΛΑΞΕΙΣ ΑΥΤΗ ΤΗ ΛΙΣΤΑ ΧΩΡΙΣ ΝΑ ΑΛΛΑΞΕΙΣ ΚΑΙ ΤΟΥ ΔΙΑΚΟΜΙΣΤΗ
//    (`apps/api/src/site/public-fields.ts`). Δύο υλοποιήσεις του ίδιου κανόνα είναι
//    δύο κανόνες, και ο ένας θα αρχίσει να λέει ψέματα.
const FALSY = new Set(['', 'false', '0', 'no', 'off', 'f', 'n', 'null', 'undefined']);

export function isSecretFlag(v: unknown): boolean {
  if (v === undefined || v === null) return false;   // απόν = δεν σημαδεύτηκε ποτέ
  if (typeof v === 'boolean') return v;
  return !FALSY.has(String(v).trim().toLowerCase());
}
