/**
 * ΤΡΙΑ ΕΠΙΠΕΔΑ, ΟΧΙ ΔΥΟ — το όραμα του George (30/7):
 *
 *   «Θέλω σίγουρα όλοι να γράφονται με ευκολία… Αλλά επιθυμώ και ένα δεύτερο
 *    επίπεδο όπου θα δίνω **μόνο εγώ** πρόσβαση στο exclusive portfolio, όπου
 *    ίσως να δείχνω ακριβή τοποθεσία του κάθε ακινήτου, ίσως περισσότερα
 *    έγγραφα, αλλά γενικά περισσότερη πρόσβαση.»
 *
 *   guest     → βλέπει τον ΔΗΜΟ. Τίποτα άλλο γεωγραφικό.
 *   member    → + την ΠΕΡΙΟΧΗ (Σάνη, Νικήτη, Βουρβουρού…). Αυτόματα με εγγραφή.
 *   exclusive → + ΑΚΡΙΒΗ ΘΕΣΗ, έγγραφα, ιδιωτική συλλογή. ΜΟΝΟ με έγκριση George.
 *
 * 🪤 ΓΙΑΤΙ ΕΝΑ ΠΕΔΙΟ ΚΑΙ ΟΧΙ ΔΥΟ BOOLEAN. Με `{member, exclusive}` γίνεται
 *    εκφράσιμη η κατάσταση «exclusive αλλά όχι member» — που δεν σημαίνει τίποτα,
 *    και κάθε έλεγχος θα έπρεπε να θυμάται να τη ακυρώνει. Με μία κλίμακα, το
 *    «τουλάχιστον μέλος» είναι μία σύγκριση και δεν ξεχνιέται.
 *
 * ⚠️ ΤΟ `exclusive` ΔΕΝ ΕΝΕΡΓΟΠΟΙΕΙΤΑΙ ΑΚΟΜΑ. Το εισιτήριο δεν κουβαλά επίπεδο
 *    (θα μπει στο `kind` του JWT μαζί με τον πίνακα συνεδριών μελών), οπότε το
 *    `viewerOf()` επιστρέφει σήμερα το πολύ `member`. Η υποδομή μπαίνει ΤΩΡΑ
 *    ώστε όταν ο George ορίσει τι ακριβώς δίνει το δεύτερο επίπεδο, να μη
 *    χρειαστεί να ξαναγραφτεί κανένα component.
 */
export type Level = 'guest' | 'agent' | 'member' | 'exclusive';

// 🪤 ΤΟ `agent` ΕΧΕΙ ΤΗΝ ΙΔΙΑ ΒΑΘΜΙΔΑ ΜΕ ΤΟΝ ΕΠΙΣΚΕΠΤΗ — ΕΠΙΤΗΔΕΣ.
//    George 6/8: ο μεσίτης «θα εγγράφεται κανονικά, αλλά δεν θα βλέπει τίποτε
//    περισσότερο από ότι ένας μη εγγεγραμμένος». Είναι ΣΥΝΔΕΔΕΜΕΝΟΣ (έχει
//    λογαριασμό, προφίλ, σελίδα συνεργασίας) αλλά η ΟΡΑΤΟΤΗΤΑ του είναι μηδενική.
//    ⛔ ΜΗΝ το μπερδέψεις με το `blocked`: εκείνο σημαίνει «πετάχτηκε έξω» (401 σε
//       κάθε διαδρομή μέλους). Ο agent μένει μέσα και βλέπει το site κανονικά.

/**
 * ⚠️ ΤΟ ΣΧΗΜΑ ΤΗΣ ΒΑΣΗΣ ΕΧΕΙ **ΔΥΟ** ΤΙΜΕΣ, ΟΧΙ ΤΡΕΙΣ (συμφωνία με EALIDA, 30/7):
 *
 *     member_level: 'member' | 'exclusive'   ← αποθηκεύεται στην επαφή
 *     guest                                   ← ΜΟΝΟ εδώ· σημαίνει «δεν υπάρχει μέλος»
 *
 * Μια επαφή με κωδικό δεν μπορεί ΠΟΤΕ να είναι `guest`. Αν το επιτρέπαμε ως
 * αποθηκευμένη τιμή, κάποιος θα το έβαζε κάποια στιγμή και μετά κανείς δεν θα
 * ήξερε τι εννοούσε — «μπλοκαρισμένος»; «εκκρεμεί»; Ίδια κατηγορία λάθους με το
 * «exclusive αλλά όχι member» που αποκλείει η κλίμακα.
 * Αν χρειαστεί ποτέ «ανακλήθηκε», είναι **άλλος άξονας** (σημαία αποκλεισμού).
 *
 * 🔴 ΚΑΙ Η ΑΠΟΥΣΙΑ ΤΟΥ ΠΕΔΙΟΥ ΔΙΑΒΑΖΕΤΑΙ **`member`**, ΠΟΤΕ «καμία πρόσβαση».
 *    Μετρήθηκε στο box 30/7: **9.830 μέλη, 0 με πεδίο `member_level`**.
 *    Αν το «λείπει» ερμηνευόταν ως «δεν έχει», την ημέρα που ανεβαίνει η
 *    καλωδίωση **9.830 άνθρωποι θα έχαναν την πρόσβασή τους ταυτόχρονα** — και
 *    θα φαινόταν σαν «χάλασε η σύνδεση», όχι σαν δική μας αλλαγή.
 *    Το `exclusive` μπαίνει ΜΟΝΟ ρητά, από την καρτέλα επαφής του CRM.
 *    ℹ️ Δώρο: το `PATCH /contacts/:id` γράφει ήδη στο ημερολόγιο με πριν/μετά,
 *       άρα το «ποιος έδωσε σε ποιον exclusive και πότε» υπάρχει χωρίς δουλειά.
 */

const RANK: Record<Level, number> = { guest: 0, agent: 0, member: 1, exclusive: 2 };

export type Viewer = {
  level: Level;
  /** Συντομογραφία «τουλάχιστον μέλος» — τη χρησιμοποιούν ήδη 6 components. */
  member: boolean;
  /** Έχει το δεύτερο επίπεδο; Ακριβής θέση, έγγραφα, ιδιωτική συλλογή. */
  exclusive: boolean;
};

/** «Φτάνει ο θεατής τουλάχιστον σε αυτό το επίπεδο;» */
export function atLeast(v: Viewer, l: Level): boolean {
  return RANK[v.level] >= RANK[l];
}

/** Ο θεατής από γνωστό επίπεδο — για σελίδες που ΕΧΟΥΝ ήδη το μέλος από τον
    δρομολογητή και δεν χρειάζεται να ξαναρωτήσουν το API. */
export function viewerFor(level: Level): Viewer {
  return { level, member: RANK[level] >= 1, exclusive: level === 'exclusive' };
}

export async function viewerOf(
  cookies: { get(n: string): { value?: string } | undefined },
): Promise<Viewer> {
  const tok = cookies.get('member_token')?.value;
  if (!tok) return viewerFor('guest');
  // ⛔ ΟΧΙ αποκωδικοποίηση του JWT εδώ: το ωφέλιμο φορτίο είναι απλό base64 και ο
  //    καθένας γράφει `{"level":"exclusive"}`. Το επίπεδο έρχεται ΜΟΝΟ από το
  //    `GET /site/member/me`, που κατέχει το μυστικό και διαβάζει τη βάση.
  const m = await memberOf(tok);
  // Άκυρο/ανακληθέν εισιτήριο ⇒ επισκέπτης. Το `blocked` το ίδιο: πετάχτηκε έξω.
  if (!m || m.blocked) return viewerFor('guest');
  return viewerFor(m.level);
}

// ── Ο ΔΗΜΟΣ — πάντα ορατός, αλλά η βάση τον γράφει με ΕΝΤΕΚΑ τρόπους ─────────
//
// Μετρήθηκε στα 527 ακίνητα (27/7):
//   247 «Κασσάνδρας» · 147 «Σιθωνίας» · 64 «Νέας Προποντίδας» · 58 «Αριστοτέλη»
//     3 «Κασσάνδρα»  ·   2 «Σιθωνία»  ·  2 «Aristotelis» (λατινικά!)
//     1 «Ν. Προποντίδα» · 1 «Αριστοτέλης» · 1 «Πολύγυρος» · 1 κενό
// Ο τροφοδότης του Onsea δίνει άλλοτε γενική («Δήμος Κασσάνδρας»), άλλοτε
// ονομαστική, άλλοτε συντομογραφία, άλλοτε λατινικά. Με απλή αντιστοίχιση
// κειμένου, 5 ακίνητα έπεφταν σε δικούς τους «δήμους» με πλήθος 1-2 και
// ΕΞΑΦΑΝΙΖΟΝΤΑΝ: η αρχική δείχνει τους 4 πρώτους δήμους, οπότε ο επισκέπτης
// δεν είχε κανέναν τρόπο να τα βρει.
//
// Λύση: πτύχωση (fold) → πίνακας συνωνύμων. Ό,τι καινούριο πετάξει ο
// τροφοδότης, μπαίνει ΜΙΑ γραμμή εδώ και διορθώνεται παντού.

/** Πτύχωση: χωρίς τόνους, πεζά, χωρίς τελείες, χωρίς καταλήξεις -ς/-σ/-s. */
function fold(s: string): string {
  return s
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')   // τόνοι
    .toLowerCase()
    .replace(/\./g, ' ')
    .split(/\s+/).filter(Boolean)
    .map((w) => w.replace(/[σςs]$/, ''))                // «Κασσάνδρας» → «κασσανδρα»
    .join(' ');
}

/** Πτυχωμένη μορφή → κανονικό όνομα (ελληνική ονομαστική). */
const MUNI_ALIAS: Record<string, string> = {
  'κασσανδρα': 'Κασσάνδρα',            'kassandra': 'Κασσάνδρα',
  'σιθωνια': 'Σιθωνία',                'sithonia': 'Σιθωνία',
  'νεα προποντιδα': 'Νέα Προποντίδα',  'ν προποντιδα': 'Νέα Προποντίδα',
  'nea propontida': 'Νέα Προποντίδα',
  'αριστοτελη': 'Αριστοτέλης',         'aristoteli': 'Αριστοτέλης',
  'πολυγυρο': 'Πολύγυρος',             'polygyro': 'Πολύγυρος',
};

/**
 * Το ΚΛΕΙΔΙ του δήμου — ελληνική ονομαστική, ίδιο σε ΟΛΕΣ τις γλώσσες και σε
 * όλες τις γραφές. Αυτό ταξιδεύει στα URL (`?municipality=Νέα Προποντίδα`) και
 * με αυτό συγκρίνει ο μετρητής. Η ΕΜΦΑΝΙΣΗ περνά από το `municipalityOf`.
 */
export function muniKey(v: Attrs | string): string {
  const raw = (typeof v === 'string' ? v : String(v?.municipality ?? '')).trim();
  if (!raw) return '';
  return MUNI_ALIAS[fold(raw)] ?? raw;
}

/**
 * Ο δήμος όπως γράφεται στη γλώσσα της σελίδας. Ένα ακίνητο = ένας δήμος.
 *
 * 🪤 Η ΣΕΙΡΑ ΤΩΝ ΕΦΕΔΡΕΙΩΝ ΕΧΕΙ ΣΗΜΑΣΙΑ. Με τη γενική `pick()` η ρουμανική
 *    σελίδα έγραφε «Κασσάνδρας» — ελληνικά, και μάλιστα σε ΓΕΝΙΚΗ πτώση, μέσα
 *    σε ρουμανικό κείμενο. Για γλώσσα με λατινικό αλφάβητο η σωστή εφεδρεία
 *    είναι το αγγλικό λατινικό («Kassandra»), όχι το ελληνικό.
 */
// Γλώσσες που πρέπει να πέσουν στο ΑΓΓΛΙΚΟ λατινικό όνομα («Kassandra»), όχι στο
// ελληνικό. Τα εβραϊκά μπαίνουν εδώ κι ας μην είναι λατινικά: μέσα σε εβραϊκή
// πρόταση το «Κασσάνδρας» θα ήταν διπλά ξένο — άλλο αλφάβητο ΚΑΙ άλλη φορά
// ανάγνωσης. Το λατινικό το διαβάζει ο Ισραηλινός αναγνώστης χωρίς πρόβλημα.
const LATIN: Lang[] = ['en', 'sr', 'de', 'ro', 'tr', 'he'];

export function municipalityOf(a: Attrs, lang: Lang): string {
  if (lang === 'el') return muniKey(a);
  const i18n = a.municipality_i18n;
  const own = typeof i18n === 'object' && i18n ? String(i18n[lang] ?? '') : '';
  if (own) return own;
  if (LATIN.includes(lang)) {
    const en = typeof i18n === 'object' && i18n ? String(i18n.en ?? '') : '';
    if (en) return en;
  }
  // Κυριλλικές γλώσσες: εφεδρεία το ΒΟΥΛΓΑΡΙΚΟ («Касандра»), όχι το ελληνικό.
  // Ο Ρώσος διαβάζει κυριλλικά χωρίς κόπο· τα «Κασσάνδρα» είναι ξένο αλφάβητο.
  const bg = typeof i18n === 'object' && i18n ? String(i18n.bg ?? '') : '';
  if ((lang === 'bg' || lang === 'ru') && bg) return bg;
  return muniKey(a);   // τελευταία εφεδρεία: ελληνική ΟΝΟΜΑΣΤΙΚΗ, ποτέ γενική
}

/** Η περιοχή — ΜΟΝΟ σε μέλη. Για τους υπόλοιπους: κενό. */
export function areaOf(a: Attrs, lang: Lang, v: Viewer): string {
  if (!v.member) return '';
  return pick(a.area_i18n, lang) || String(a.area ?? '');
}

/** Ο τόπος όπως εμφανίζεται: περιοχή αν είναι μέλος, αλλιώς δήμος. */
export function placeOf(a: Attrs, lang: Lang, v: Viewer): string {
  return areaOf(a, lang, v) || municipalityOf(a, lang);
}

/** Πόσες περιοχές μένουν κλειδωμένες — το νούμερο που κάνει την προτροπή συγκεκριμένη. */
export function lockedAreaCount(all: Attrs[], lang: Lang): number {
  const s = new Set<string>();
  for (const a of all) {
    const x = pick(a.area_i18n, lang) || a.area;
    if (x) s.add(String(x));
  }
  return s.size;
}

