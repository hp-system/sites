/** Πώς λέγεται η κάθε γλώσσα ΣΤΗ ΓΛΩΣΣΑ ΤΗΣ — ποτέ «Bulgarian» σε Βούλγαρο. */
export const LANG_NAME: Record<Lang, string> = {
  el: 'Ελληνικά', en: 'English', bg: 'Български', sr: 'Srpski', de: 'Deutsch', ro: 'Română',
  tr: 'Türkçe', he: 'עברית', ru: 'Русский',
};

// 🪤 ΔΙΚΛΕΙΔΑ: καμία γλώσσα δεν διαφημίζεται πριν έχει κείμενα.
// Το `hreflang` προς σελίδα που δεν υπάρχει (ή υπάρχει στα αγγλικά) είναι
// ΧΕΙΡΟΤΕΡΟ από καθόλου hreflang: η Google απορρίπτει ολόκληρο το σύμπλεγμα.
// Αν λείπει έστω και ένα κλειδί, η γλώσσα δεν δημοσιεύεται — και φαίνεται εδώ.
const KEYS = Object.keys(T.el);
export const PUBLISHED: Lang[] = LANGS.filter((l) => KEYS.every((k) => T[l]?.[k]));

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  let s = T[lang]?.[key] ?? T.el[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  // 🪤 Δικλείδα: κείμενο με placeholder που έμεινε αγέμιστο φεύγει ΣΙΩΠΗΛΑ στη
  //    σελίδα («Имоти в Гърция — {n} оферти»). Έγινε ακριβώς αυτό όταν μπήκε
  //    αριθμός στο meta.title ενώ ο καλών περνούσε μεταβλητές μόνο στο desc.
  //    Δεν πετάμε σφάλμα — μια σελίδα δεν πέφτει για έναν τίτλο — αλλά φωνάζει.
  if (s.includes('{') && /\{[a-z]\w*\}/i.test(s)) {
    console.warn(`[i18n] ${lang}/${key}: αγέμιστο placeholder → «${s}»`);
  }
  return s;
}
