export const LANGS = ['el', 'en', 'bg', 'sr', 'de', 'ro', 'tr', 'he', 'ru'] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = 'el';

/**
 * Γλώσσες που γράφονται από δεξιά προς τα αριστερά.
 * Καθορίζει το `dir` του <html> — και μαζί ΟΛΗ τη γεωμετρία της σελίδας, γιατί
 * το CSS χρησιμοποιεί logical properties (margin-inline, padding-inline, start/end).
 */
export const RTL: readonly Lang[] = ['he'];
export const isRTL = (lang: Lang): boolean => RTL.includes(lang);

/** Το prefix του URL. Η ελληνική είναι η προεπιλογή και δεν παίρνει prefix. */
export function prefix(lang: Lang): string {
  return lang === DEFAULT_LANG ? '' : `/${lang}`;
}

