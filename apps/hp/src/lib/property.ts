/**
 * Η ΟΥΡΑ «(possibly generated by AI)» ΣΤΟ ΤΕΛΟΣ ΤΩΝ ΠΕΡΙΓΡΑΦΩΝ (#45).
 * Μετρήθηκε 21/10: 100+ περιγραφές σε el/en/bg/de/sr, ~20 παραλλαγές διατύπωσης
 * («(ενδεχομένως δημιουργήθηκε από AI)», «(möglicherweise durch KI generiert)»…).
 * Ο AI Act (άρθρο 50) ΔΕΝ τη ζητά για περιγραφές ακινήτων — Κατευθυντήριες Γραμμές
 * C(2026) 5054 §131 — και το «ίσως» δείχνει αβεβαιότητα. George 21/10: σήμανση μόνο
 * όπου είναι υποχρεωτική. Κόβεται ΜΟΝΟ στο τέλος και ΜΟΝΟ αν η παρένθεση λέει AI/KI.
 */
const AI_TAIL = /\s*[(\[][^()\[\]]{0,80}\b(?:AI|KI)\b[^()\[\]]{0,20}[)\]]\s*$/;
export function stripAiTail(s: string): string {
  return s.replace(AI_TAIL, '').trim();
}

/** Περιγραφή στη γλώσσα της σελίδας. Υπάρχουν μόνο el/en/bg/de/sr → εφεδρεία en. */
export function descriptionOf(a: Attrs, lang: Lang): string {
  const d = (k: string) => stripAiTail(String((a as Record<string, unknown>)[`description_${k}`] ?? '').trim());
  return d(lang) || d('en') || d('el');
}
/** The language the description above is actually in (#251: ro/tr/he have none in the CRM yet; the English
 *  one is shown, marked lang="en" so readers and search engines read it as English). */
export function descriptionLangOf(a: Attrs, lang: Lang): Lang {
  const has = (k: string) => !!stripAiTail(String((a as Record<string, unknown>)[`description_${k}`] ?? '').trim());
  return has(lang) ? lang : has('en') ? 'en' : 'el';
}

/**
 * ΕΝΑ ΧΑΡΑΚΤΗΡΙΣΤΙΚΟ — σταθερό αναγνωριστικό + ετικέτα προς εμφάνιση.
 *
 * Ο George επέλεξε (5/8) το **σημασιολογικό slug δίπλα στην τιμή**: το EALIDA θα
 * δίνει `{ slug: 'fireplace', label: 'Τζάκι' }`. Έτσι οι διατυπώσεις μπορούν να
 * ξαναγραφούν ελεύθερα σε 9 γλώσσες χωρίς να αγγίξουν τίποτα εδώ.
 */
export type Feature = {
  /** English (and Greek) label at the same position — only for choosing the icon. */
  key?: string; slug?: string; label: string };

/**
 * Διαβάζει ΚΑΙ ΤΑ ΔΥΟ σχήματα, ώστε να μη χρειαστεί δεύτερο πέρασμα:
 *   · ΣΗΜΕΡΑ (παλιό hp-api): `features_el` = πίνακας ΣΚΕΤΟΥ ΚΕΙΜΕΝΟΥ
 *   · ΑΥΡΙΟ (EALIDA): `features` = πίνακας αντικειμένων με `slug`/`code` + `label`
 *
 * 🪤 ΤΑ ΧΑΡΑΚΤΗΡΙΣΤΙΚΑ ΔΕΝ ΕΙΝΑΙ ΕΝΑ ΠΕΔΙΟ — ΕΙΝΑΙ ΠΕΝΤΕ. Στο EALIDA ζουν σε
 *    `extras` (78 επιλογές) · `views` (7) · `pools` (6) · `floor_materials` (9) ·
 *    `frames` (6). Αν το `features` έρθει ενοποιημένο, τα διαβάζουμε όλα από εκεί·
 *    αλλιώς προσθέτουμε πηγές ΕΔΩ, σε ένα σημείο, όχι στο component.
 */
export function featuresOf(a: Attrs, lang: Lang): Feature[] {
  const rec = a as Record<string, unknown>;

  // ── Νέο σχήμα: αντικείμενα με σταθερό αναγνωριστικό ──────────────────────
  const structured = rec.features;
  if (Array.isArray(structured) && structured.some((x) => x && typeof x === 'object')) {
    return (structured as Record<string, unknown>[])
      .map((f) => {
        const label = String(f.label ?? f.name ?? f.title ?? '').trim();
        const slug = String(f.slug ?? f.code ?? '').trim();
        return label || slug ? { slug: slug || undefined, label: label || slug } : null;
      })
      .filter(Boolean) as Feature[];
  }

  // ── Σημερινό σχήμα: σκέτο κείμενο, χωρίς αναγνωριστικό ───────────────────
  const g = (k: string) => {
    const v = rec[`features_${k}`];
    return Array.isArray(v) ? v.map(String).map((x) => x.trim()).filter(Boolean) : [];
  };
  const own = g(lang);
  const list = own.length ? own : (g('en').length ? g('en') : g('el'));
  // The lists are parallel (same order in every language): the English one names the icon,
  // so a German or Russian page gets the same pictures (Sergei 03/11).
  const en = g('en'), el = g('el');
  return list.map((label, i) => ({ label, key: `${en.length === list.length ? en[i] : ''} ${el.length === list.length ? el[i] : ''}`.trim() || undefined }));
}

